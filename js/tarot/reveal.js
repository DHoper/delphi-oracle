// 她的反應：神諭對她也可能出乎意料。先叫出牌名，再帶一點當下的情緒（驚訝、鬆一口氣、遲疑）
const HEAVY = new Set([13, 15, 16]); // 死神、惡魔、高塔：正位現身時，她也會一怔
function react(c, order, R) {
  const pick = arr => arr[(R.seed + c.id * 7 + order * 3) % arr.length], nm = c.name;
  if (!c.rev && HEAVY.has(c.id)) return pick([`……是${nm}。我沒料到它會在這裡。`, `嗯……${nm}。`, `竟然是${nm}。`]);
  if (c.score >= 2 && !c.rev) return pick([`啊，是${nm}。`, `哦，${nm}。`, `是${nm}，好。`]);
  if (c.rev && c.score <= -1) return pick([`${nm}，倒過來的。`, `嗯……${nm}，逆著來。`, `是${nm}，可惜是倒的。`]);
  if (c.rev) return pick([`${nm}，倒過來了。`, `是${nm}，逆著的。`]);
  if (order > 0 && c.score <= -1) return pick([`咦，是${nm}。`, `${nm}……`]);
  return pick([`是${nm}。`, `${nm}。`]);
}

// 第一張翻開後還要等：她只說到這裡
const WAIT = ["先別急，等其他牌翻開，才看得清。", "這張先放著，要和後面的牌一起看。", "我先記著它，還要看另外兩張。"];

const tone = c => (c.score >= 1 ? 1 : c.score <= -1 ? -1 : 0);
// 和前一張翻開的牌比較
function relate(R, prev, cur, last) {
  const a = tone(prev), b = tone(cur), sp = R.spread.id;
  if (sp === "choice" && ["左徑", "右徑"].includes(prev.position) && ["左徑", "右徑"].includes(cur.position)) {
    const d = cur.score - prev.score;
    return d >= 1 ? "比起另一條路，這條走起來順一些。" : d <= -1 ? "比起另一條路，這條要費力一些。" : "兩條路的分量差不多。";
  }
  if (a > 0 && b > 0) return "跟剛才那張是同一股光。";
  if (a > 0 && b < 0) return "剛才那張還那麼亮，這裡卻有陰影。";
  if (a < 0 && b > 0) return "前一張的陰影，到這裡透出光來了。";
  if (a < 0 && b < 0) return last ? "又是一張沉的。" : "又是一張沉的。先別慌，還有一張。";
  if (prev.rev && cur.rev) return "又是逆著來的。";
  return last ? "" : "還差一張。";
}

/**
 * 第 order 張翻開的牌（從 0 起算）要說的話。
 * R：解牌引擎的結果；k：這張牌的牌位；order：這是第幾張翻開的；prevK：前一張翻開的牌位（第一張時為 -1）
 * 回傳 { text, tail }：text 是開場＋第一眼，tail 是收尾（可能為空）
 */
export function revealLine(R, k, order, prevK) {
  const c = R.cards[k], n = R.cards.length, last = order === n - 1;
  const lead = (LEAD[c.position] || ["", ""])[order === 0 ? 0 : 1];
  const text = lead + react(c, order, R) + (GLIMPSE[c.id] ? GLIMPSE[c.id][c.rev ? 1 : 0] : "");
  let tail = "";
  if (n > 1) {
    if (order === 0) tail = WAIT[(R.seed + k) % WAIT.length];
    else {
      tail = relate(R, R.cards[prevK], c, last);
      if (last) tail = (tail ? tail : "") + "三張都在這裡了。";
    }
  }
  return { text, tail };
}

