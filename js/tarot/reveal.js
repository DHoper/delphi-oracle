  dim: ["剛才還亮著……怎麼暗了……", "光不見了……剛才明明還在……", "暗下來了……跟剛才不一樣……"],
  dawn: ["黑裡面……透出光來了。", "剛才那麼暗……這裡卻亮了。", "有光了……總算有光了……"],
  dark: ["又是暗的……怎麼都是暗的……", "還是沒有光……", "跟剛才一樣沉……"],
  turned: ["又倒過來了……", "又是反著的……"],
  more: ["……還有一張。", "……還沒完。"]
