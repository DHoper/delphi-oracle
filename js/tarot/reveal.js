const HEAVY = new Set([13, 15, 16]); // 死神、惡魔、高塔：正位現身時，她會先驚一下
// 被神諭攫住的那一下：凶兆先倒抽一口氣，其餘只是一聲低吟或沉默
function onset(c, order, R) {
  const pick = arr => arr[(R.seed + c.id * 7 + order * 3) % arr.length];
  if ((!c.rev && HEAVY.has(c.id)) || c.score <= -2) return pick(["啊……", "不……等等……", "……"]);
  if (c.rev) return pick(["這……", "等等……", "嗯……不對……", "……"]); // 逆位：遲疑
  if (order === 0) return pick(["……", "嗯……", ""]);
  return pick(["……", ""]);
}

// 第一張說完：還沒看完
const WAIT = ["……煙尚未散。", "……尚有牌在候。"];

const tone = c => (c.score >= 1 ? 1 : c.score <= -1 ? -1 : 0);
// 和前一張翻開的牌比較：她感覺到的光與暗（每種情況幾種說法）
const REL = {
  better: ["此路……較方才明亮。", "此路，行之較順。"],
  worse: ["此路……較方才沉重。", "此路，荊棘較多。"],
  even: ["兩路……輕重相當。", "兩邊……難分軒輊。"],
  bright: ["光仍在……一如方才。", "依然明亮。"],
  dim: ["方才猶亮……何以暗了？", "光……淡了……"],
  dawn: ["方才那般幽暗……此處透出光來。", "有光了……終於有光。"],
  dark: ["又是幽暗……", "依然……不見光……"],
  turned: ["又是倒懸……", "又倒轉了……"],
  more: ["……尚未完。", "……還有。"]
};
function relate(R, prev, cur, k) {
  const a = tone(prev), b = tone(cur), sp = R.spread.id, pick = arr => arr[(R.seed + k * 3) % arr.length];
  if (sp === "choice" && ["左徑", "右徑"].includes(prev.position) && ["左徑", "右徑"].includes(cur.position)) {
    const d = cur.score - prev.score;
    return pick(d >= 1 ? REL.better : d <= -1 ? REL.worse : REL.even);
  }
  if (a > 0 && b > 0) return pick(REL.bright);
  if (a > 0 && b < 0) return pick(REL.dim);
  if (a < 0 && b > 0) return pick(REL.dawn);
  if (a < 0 && b < 0) return pick(REL.dark);
  if (prev.rev && cur.rev) return pick(REL.turned);
  return "";
}
// 最後一張說完：回過神來
const BACK = ["……煙散了。所見已盡。", "……煙，緩緩退去。", "……所見，止於此。"];

/**
 * 第 order 張翻開的牌（從 0 起算）要說的話。
 * R：解牌引擎的結果；k：這張牌的牌位；order：這是第幾張翻開的；prevK：前一張翻開的牌位（第一張時為 -1）
 * 回傳 { lead, text, tail, heavy }：lead 在牌面還沒完全露出時就開口；text 是異象，等牌面露出才說；
 * tail 是回過神的一句；heavy 表示凶兆（說得慢、會驚呼）
 */
export function revealLine(R, k, order, prevK) {
  const c = R.cards[k], n = R.cards.length, last = order === n - 1;
  const leads = LEAD[c.position] || [""], lead = onset(c, order, R) + leads[(R.seed + k * 7) % leads.length];
  const text = vision(R, c);
  let tail = "";
  const rel = n > 1 && order > 0 ? relate(R, R.cards[prevK], c, k) : "";
  if (!last) tail = order === 0 ? WAIT[(R.seed + k) % WAIT.length] : rel || REL.more[(R.seed + k) % 2];
  else tail = (rel ? rel + "\n" : "") + BACK[(R.seed + k) % BACK.length];
  return { lead, text, tail, heavy: (!c.rev && HEAVY.has(c.id)) || c.score <= -2 };
}

/** 給 AI 的參考：揭牌時對每張牌說過的異象（不含順序相關的收尾） */
export const glimpses = R => R.cards.map(c => `${c.position}：${vision(R, c)}`);
