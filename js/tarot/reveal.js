  dim: ["方才尚亮……何以轉暗……", "光消逝……方才明明猶在……", "轉暗……與方才迥異……"],
  dawn: ["黑暗之中……透出光來……", "方才那般幽暗……此處卻亮……", "有光……終於有光……"],
  dark: ["又是幽暗……何以盡是幽暗……", "依然不見光……", "沉重……一如方才……"],
  turned: ["又倒轉……", "又是逆行……"],
  more: ["……尚有一張……", "……未完……"]
